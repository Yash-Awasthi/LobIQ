// Execution-quality report in the spirit of SEC Rule 605 for a stored Nasdaq day (src/surveil/best_ex.hpp):
// per symbol and per order size, effective spread split into realized spread and price impact, and the
// share of volume executed inside the quote with its price improvement. Prints Markdown.
// Usage: itch_bestex <store> [SYMBOL,...] [--top N]   (default: the N = 25 most active symbols)

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <string>
#include <vector>

#include "core/parallel.hpp"
#include "data/store.hpp"
#include "surveil/best_ex.hpp"

namespace {

using namespace hft;

void row(const char* label, const surveil::ExecBucket& b) {
    if (b.shares <= 0) return;
    const double c = 100 / b.shares;  // dollars summed over shares -> cents per share
    std::printf("| %s | %.0f | %.0f | %.3f | %.3f | %.3f | %.1f%% | %.3f |\n", label, b.execs, b.shares, b.eff * c,
                b.real * c, b.impact * c, 100 * b.hidden_shares / b.shares,
                b.hidden_shares > 0 ? 100 * b.improved / b.hidden_shares : 0.0);
}

}  // namespace

int main(int argc, char** argv) {
    constexpr const char* usage = "usage: itch_bestex <store> [SYMBOL,...] [--top N]";
    std::size_t top = 25;
    std::vector<const char*> pos;
    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--top") == 0 && i + 1 < argc) top = std::strtoul(argv[++i], nullptr, 10);
        else if (argv[i][0] == '-') return std::fprintf(stderr, "%s\n", usage), 2;
        else pos.push_back(argv[i]);
    }
    if (pos.empty() || pos.size() > 2 || top == 0) return std::fprintf(stderr, "%s\n", usage), 2;
    const std::filesystem::path dir = pos[0];
    const auto names = data::read_symbols(dir);
    if (names.empty()) return std::fprintf(stderr, "no symbols.tsv in %s\n", dir.c_str()), 2;

    std::vector<std::pair<std::string, std::uint16_t>> syms;
    if (pos.size() == 2) {
        for (std::string s = pos[1]; !s.empty();) {
            const std::size_t c = s.find(',');
            const std::string name = s.substr(0, c);
            if (!names.contains(name)) return std::fprintf(stderr, "symbol %s not in %s\n", name.c_str(), dir.c_str()), 2;
            syms.emplace_back(name, names.at(name));
            s = c == std::string::npos ? "" : s.substr(c + 1);
        }
    } else {  // the most active symbols by message count, from the store index
        std::vector<std::pair<std::uint64_t, std::string>> active;
        for (const auto& [name, loc] : names) {
            std::uint64_t n = 0;
            for (const auto& e : data::SymbolReader(dir, loc).index()) n += e.n_msgs;
            active.emplace_back(n, name);
        }
        std::sort(active.rbegin(), active.rend());
        for (std::size_t i = 0; i < std::min(top, active.size()); ++i) syms.emplace_back(active[i].second, names.at(active[i].second));
    }

    std::vector<std::array<surveil::ExecBucket, surveil::BestEx::kSizes>> res(syms.size());
    parallel_for(syms.size(), [&](std::size_t i) {
        surveil::BestEx b;
        data::SymbolReader rd(dir, syms[i].second);
        data::Record rec{};
        while (rd.next(rec)) b.on_message(rec.data, rec.len);
        res[i] = b.buckets();
    });

    std::printf("# Execution quality: %s\n\n", dir.filename().c_str());
    std::printf("Generated by `itch_bestex`, 09:35 to 15:50 ET, Nasdaq's book only, in the spirit of SEC Rule 605. "
                "Every execution is signed by its taker. Effective half-spread: the price against the mid just before the "
                "trade; realized spread: against the mid 5 s later, what the resting side kept; price impact: how far "
                "the mid moved with the taker (effective = realized + impact). Inside the quote: shares executed against "
                "hidden orders strictly between the bid and the ask, and their price improvement over the displayed "
                "quote. Cents per share, weighted by shares.\n\n");
    const char* head = "| %s | Executions | Shares | Effective half-spread (c/sh) | Realized (c/sh) | Impact (c/sh) | Inside the quote | Improvement (c/sh) |\n"
                       "|---|---|---|---|---|---|---|---|\n";
    std::printf("## By symbol\n\n");
    std::printf(head, "Symbol");
    std::array<surveil::ExecBucket, surveil::BestEx::kSizes> all{};
    for (std::size_t i = 0; i < syms.size(); ++i) {
        surveil::ExecBucket sum;
        for (std::size_t k = 0; k < surveil::BestEx::kSizes; ++k) sum.add(res[i][k]), all[k].add(res[i][k]);
        row(syms[i].first.c_str(), sum);
    }
    std::printf("\n## By execution size, all %zu symbols\n\n", syms.size());
    std::printf(head, "Shares per execution");
    const char* label[] = {"1-100", "101-500", "501-2,000", "over 2,000"};
    for (std::size_t k = 0; k < surveil::BestEx::kSizes; ++k) row(label[k], all[k]);
    return 0;
}
