#!/usr/bin/env bash
# Walk-forward check of the imbalance-filtered maker (strategies/imbalance.cpp): the threshold is
# chosen on the train days by total PnL, then scored unchanged on the test days next to the
# plain joiner (threshold 1 never steps back). Prints Markdown (docs/results/maker-walkforward.md).
set -euo pipefail
d=${HFT_DATA:-$HOME/data}
b=${HFT_BUILD:-$(dirname "$0")/../build/native}
syms=${SYMBOLS:-SPY,QQQ,IWM,SOXL,SQQQ,TQQQ,IBIT,TNA,INTC,NVDA}
train=(S120825 S120925)
test=(S121025 S121125 S121225 S061226)
grid=0.0,0.05,0.1,0.2,0.3,0.5,0.7,1.0
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Fee scenarios (micro-dollars per share; assumed, the published tiers vary by member volume):
# a mid-tier Nasdaq rebate under the 30 mil access-fee cap, a scaled rebate under the 10 mil cap
# of amended Rule 610, both with Section 31 ($27.80 per $1M sold, fiscal 2025) and FINRA TAF.
reg="sec_fee_per_million=27800000 taf_per_share=166 taf_max=8300000"
declare -A fees=([none]="maker_rebate=0" [cap30]="maker_rebate=2000 $reg" [cap10]="maker_rebate=700 $reg")
declare -A title=([none]="No fees or rebates" [cap30]="30 mil cap: rebate \$0.0020 per share, Section 31 and TAF on sells"
                  [cap10]="10 mil cap (amended Rule 610): rebate \$0.0007 per share, Section 31 and TAF on sells")
run() {  # day thresholds scenario -> rows: symbol threshold total spread inventory fees fills
    # shellcheck disable=SC2086
    "$b/apps/itch_backtest" "$d/store-$1-v50" "$syms" imbalance ${fees[$3]} --sweep threshold="$2" | tail -n +2
}
day() { echo "20${1:5:2}-${1:1:2}-${1:3:2}"; }

echo "# Walk-forward maker test"
echo
echo "Generated by \`scripts/maker_walkforward.sh\`. Strategy: \`imbalance\` (joins the best bid and ask,"
echo "pulls the side the top-of-book imbalance points against when |imbalance| exceeds the threshold;"
echo "100 shares, inventory cap 500). Symbols: ${syms//,/, }. Train: $(day ${train[0]}), $(day ${train[1]});"
echo "test: $(for t in "${test[@]}"; do day "$t"; done | paste -sd, | sed 's/,/, /g'). The threshold is picked on the train days by summed"
echo "PnL over all symbols and both days; the test days use it unchanged. Backtester: queue-position"
echo "fills against the real order flow, zero latency (docs/STRATEGIES.md)."
for scenario in none cap30 cap10; do
    echo
    echo "## ${title[$scenario]}"
    echo
    for t in "${train[@]}"; do run "$t" "$grid" "$scenario"; done > "$tmp/train"
    best=$(awk '{s[$2]+=$3} END{b=""; for (k in s) if (b=="" || s[k]>s[b]) b=k; print b}' "$tmp/train")
    cp "$tmp/train" "$tmp/$scenario-train"
    echo "Train PnL by threshold (USD, all symbols, both days):"
    echo
    echo "| Threshold | Total | Spread | Inventory |"
    echo "|---|---|---|---|"
    awk '{t[$2]+=$3; s[$2]+=$4; i[$2]+=$5} END{for (k in t) printf "| %s | %.0f | %.0f | %.0f |\n", k, t[k], s[k], i[k]}' "$tmp/train" | sort -t'|' -k2 -n
    echo
    echo "Chosen threshold: **$best**."
    echo
    for t in "${test[@]}"; do run "$t" "$best,1.0" "$scenario" | sed "s/^/$t\t/"; done > "$tmp/test"
    echo "Test days (USD per symbol, all test days summed):"
    echo
    echo "| Symbol | Joiner total | Joiner inventory | Filtered total | Filtered inventory | Fills joiner / filtered |"
    echo "|---|---|---|---|---|---|"
    awk -v best="$best" '{k=$2; if ($3=="1.0"||$3=="1") {nt[k]+=$4; ni[k]+=$6; nf[k]+=$8} if ($3==best) {ft[k]+=$4; fi_[k]+=$6; ff[k]+=$8}}
        END{for (k in nt) printf "| %s | %.0f | %.0f | %.0f | %.0f | %d / %d |\n", k, nt[k], ni[k], ft[k], fi_[k], nf[k], ff[k];
            for (k in nt) {a+=nt[k]; c+=ft[k]; if (ft[k]>nt[k]) w++; n++}
            printf "\nTotal: joiner %.0f, filtered %.0f; the filter does better on %d of %d symbols.\n", a, c, w, n}' "$tmp/test"
done

echo
echo "## Latency"
echo
echo "The same two strategies on the test days, no fees, with market data and order entry each"
echo "delayed by the one-way latency shown (the live path measures about 9 us from kernel receive"
echo "to decision, docs/exec/PERF.md R16; a co-located venue round trip adds a few microseconds)."
echo
best=$(awk '{s[$2]+=$3} END{b=""; for (k in s) if (b=="" || s[k]>s[b]) b=k; print b}' "$tmp/none-train")
echo "| One-way latency | Joiner total | Filtered total | Filtered fills |"
echo "|---|---|---|---|"
for ns in 0 5000 50000 500000 5000000; do
    for t in "${test[@]}"; do
        "$b/apps/itch_backtest" "$d/store-$t-v50" "$syms" imbalance market_data_ns=$ns order_entry_ns=$ns \
            --sweep threshold="$best,1.0" | tail -n +2
    done | awk -v ns=$ns -v best="$best" '{if ($2=="1.0"||$2=="1") j+=$3; if ($2==best) {f+=$3; n+=$7}}
        END{lat = ns >= 1000000 ? sprintf("%g ms", ns/1e6) : ns >= 1000 ? sprintf("%g us", ns/1e3) : "0";
            printf "| %s | %.0f | %.0f | %d |\n", lat, j, f, n}'
done
