#!/usr/bin/env bash
# One unattended session on the bare-metal machine: build, every check that needs real data or
# hardware, the newer tools on stored Nasdaq days, and what to back up before the install goes.
# Writes docs/results/session-<date>.md; commit and push it afterwards (docs/BARE_METAL.md, section 7).
# Usage: scripts/arch_session.sh [--bench]   --bench also re-measures peak timing (needs root, about 1 h)
set -u
cd "$(dirname "$0")/.."
d=${HFT_DATA:-$HOME/data}
B=build/native/apps
train=${TRAIN:-S120825} test=${TEST:-S121025}
syms=${SYMBOLS:-SPY,QQQ,AAPL,MSFT,NVDA,AMD,INTC,TSLA}
venue="maker_rebate=2000 taker_fee=3000 market_data_ns=50000 order_entry_ns=20000"
out=docs/results/session-$(date +%F).md
log=$(mktemp -d)
pass=() fail=() skip=()

step() {  # name command...: runs it, keeps its output in $log/name.log
    local name=$1
    shift
    printf '== %-22s' "$name"
    if "$@" >"$log/$name.log" 2>&1; then pass+=("$name"); echo ok; else fail+=("$name"); echo "FAILED ($log/$name.log)"; fi
}
have_store() { [ -d "$d/store-$1-v50" ]; }

step build bash -c 'cmake --preset native && cmake --build build/native'
step tests ctest --test-dir build/native --output-on-failure -j"$(nproc)"
step cli scripts/check_cli.sh "$B"
step security scripts/security_gates.sh
step demos env HFT_BIN="$B" scripts/demo/all.sh out
if compgen -G "$d/pm-live/2*/session.tsv" >/dev/null; then
    step parity bash -c "PM_LIVE=$B/pm_live scripts/check_parity.sh | tee $log/parity.txt && ! grep -q DIFF $log/parity.txt"
else
    skip+=("parity (no recordings in $d/pm-live)")
fi
stores=("$d"/store-S*-v50)
if [ -d "${stores[0]}" ]; then
    step checkpoints bash -c 'for s in "$@"; do '"$B"'/checkpoint "$s" --verify || exit 1; done' _ "${stores[@]}"
else
    skip+=("checkpoints (no stores in $d)")
fi

{
    echo "# Bare-metal session, $(date +%F)"
    echo
    echo "Generated by \`scripts/arch_session.sh\` on $(uname -n), $(uname -r), commit $(git rev-parse --short HEAD)."
    echo "CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | sed 's/^ //'). Venue for every backtest: $venue."
    echo
    echo "Passed: ${pass[*]:-none}. Failed: ${fail[*]:-none}. Skipped: ${skip[*]:-none}."
} >"$out"

if have_store "$test"; then
    echo "== strategies on $test"
    {
        echo
        echo "## Market makers on a real day ($test)"
        echo
        echo "Each symbol run on its own; one-minute Sharpe annualised, PSR = P(true Sharpe > 0)."
        for s in naive imbalance microprice; do
            echo
            echo "### $s"
            echo
            "$B/itch_backtest" "$d/store-$test-v50" "$syms" "$s" $venue 2>/dev/null |
                awk -F'\t' 'NR == 1 {print "| symbol | total USD | fills | max inventory | Sharpe | PSR |"; print "|---|---|---|---|---|---|"; next}
                            {print "| " $1 " | " $2 " | " $6 " | " $7 " | " $9 " | " $10 " |"}'
        done
    } >>"$out"
else
    skip+=("strategies (no store $test)")
fi

if have_store "$train" && have_store "$test"; then
    echo "== microprice walk-forward"
    sweep=$("$B/itch_backtest" "$d/store-$train-v50" "$syms" microprice $venue \
        --sweep edge_ticks=0,0.5,1 --sweep skew_ticks=0,0.5,1 2>/dev/null)
    best=$(echo "$sweep" | awk -F'\t' 'NR > 1 {t[$2 "\t" $3] += $4} END {for (k in t) if (b == "" || t[k] > t[b]) b = k; print b}')
    edge=$(echo "$best" | cut -f1) skew=$(echo "$best" | cut -f2)
    {
        echo
        echo "## Micro-price maker, walk-forward"
        echo
        echo "Nine settings of edge_ticks and skew_ticks on $train, summed over symbols; the best one"
        echo "(edge_ticks=$edge, skew_ticks=$skew) then runs unchanged on $test."
        echo
        echo "| edge | skew | train total USD (all symbols) | lowest DSR among symbols |"
        echo "|---|---|---|---|"
        echo "$sweep" | awk -F'\t' 'NR > 1 {k = $2 " | " $3; t[k] += $4; if (!(k in m) || $13 < m[k]) m[k] = $13}
                                    END {for (k in t) printf "| %s | %.2f | %s |\n", k, t[k], m[k]}' | sort
        echo
        echo "Test day:"
        echo
        "$B/itch_backtest" "$d/store-$test-v50" "$syms" microprice $venue edge_ticks="$edge" skew_ticks="$skew" 2>/dev/null |
            awk -F'\t' 'NR == 1 {print "| symbol | total USD | Sharpe | PSR |"; print "|---|---|---|---|"; next}
                        {s += $2; print "| " $1 " | " $2 " | " $9 " | " $10 " |"} END {printf "| all | %.2f | | |\n", s}'
    } >>"$out"
else
    skip+=("walk-forward (needs stores $train and $test)")
fi

if have_store "$test"; then
    echo "== markov on $test"
    {
        echo
        echo "## Markov chain of the book ($test)"
        echo
        echo "Counts from 09:35 to 12:45, scored on every mid move from 12:45 to 15:55."
        echo
        echo "| symbol | afternoon moves | hit rate | always one direction | edge (points) |"
        echo "|---|---|---|---|---|"
        for s in ${syms//,/ }; do
            "$B/itch_markov" "$d/store-$test-v50" "$s" --json 2>/dev/null |
                python3 -c 'import json, sys; m = json.load(sys.stdin); t = m["test"]
print("| %s | %d | %.1f%% | %.1f%% | %+.1f |" % (m["symbol"], t["moves"], 100 * t["hit_rate"], 100 * t["baseline"], 100 * (t["hit_rate"] - t["baseline"])))'
        done
    } >>"$out"
fi

if [ "${1:-}" = --bench ]; then
    step pgo scripts/pgo.sh "$d/store-$test-v50"
    if sudo NO_TURBO=0 scripts/tune.sh >"$log/tune.log" 2>&1; then
        step bench bash -c 'scripts/bench_max.sh > docs/results/max-performance.md'
    else
        fail+=("tune")
    fi
fi

{
    echo
    echo "## Back up before removing the install"
    echo
    echo "Live recordings cannot be downloaded again; Nasdaq days can (\`hft get\`) while Nasdaq keeps them."
    echo
    echo '```'
    du -sh "$d"/pm-live "$d"/pm "$d"/live "$d"/reports 2>/dev/null
    du -sh "$d"/store-S*-v50 2>/dev/null | sort -k2
    echo '```'
} >>"$out"

echo
echo "results: $out"
echo "passed: ${pass[*]:-none}"
echo "failed: ${fail[*]:-none}"
echo "skipped: ${skip[*]:-none}"
echo "logs: $log"
[ ${#fail[@]} -eq 0 ]
