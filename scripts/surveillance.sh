#!/usr/bin/env bash
# Surveillance over every stored day (docs/results/surveillance.md): candidate counts per day, then
# the full report for one day (DAY, default S121025).
set -euo pipefail
d=${HFT_DATA:-$HOME/data}
b=${HFT_BUILD:-$(dirname "$0")/../build/native}
days=${DAYS:-S101819 S112825 S120825 S120925 S121025 S121125 S121225 S061226}
detail=${DAY:-S121025}
echo "# Market surveillance"
echo
echo "Generated by \`scripts/surveillance.sh\` with \`itch_surveil\` (rules in the report below). Candidate"
echo "counts per stored day:"
echo
echo "| Day | Symbols | Spoofing | Layering | Quote stuffing |"
echo "|---|---|---|---|---|"
for x in $days; do
    out=$("$b/apps/itch_surveil" "$d/store-$x-v50" --top 1)
    n=$(echo "$out" | grep -oE 'over [0-9]+ symbols' | grep -oE '[0-9]+')
    row() { echo "$out" | awk -F'|' -v k="$1" '$2 ~ k {gsub(/ /, "", $3); gsub(/ /, "", $4); print $3 " (" $4 " symbols)"}'; }
    echo "| 20${x:5:2}-${x:1:2}-${x:3:2} | $n | $(row Spoofing) | $(row Layering) | $(row "Quote stuffing") |"
done
echo
"$b/apps/itch_surveil" "$d/store-$detail-v50" --top 15 | sed 's/^# Surveillance report: /## Full report: /; s/^## /### /; s/^### Full report/## Full report/'
