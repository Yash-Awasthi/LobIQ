#!/usr/bin/env bash
# Walk-forward test of the leader filter (strategies/leader.cpp) on products that follow another
# (docs/results/lead-lag.md). One lead_bp for all pairs, chosen on the train days by summed PnL,
# then scored unchanged on the test days against the same maker without it (lead_bp=1000).
# Prints Markdown (docs/results/leader-walkforward.md).
set -euo pipefail
d=${HFT_DATA:-$HOME/data}
b=${HFT_BUILD:-$(dirname "$0")/../build/native}
pairs=${PAIRS:-TQQQ:QQQ SQQQ:QQQ:-1 QQQM:QQQ IVV:SPY VOO:SPY UPRO:SPY TNA:IWM NVDL:NVDA TSLL:TSLA SOXL:SMH GOOG:GOOGL FBTC:IBIT}
train=(S120825 S120925)
read -ra test <<< "${TEST:-S121025 S121125 S121225 S061226}"
grid=0,0.02,0.05,0.1,0.2,0.5,1,2,5,1000
rebate=${REBATE:-0}
day() { echo "20${1:5:2}-${1:1:2}-${1:3:2}"; }
run() {  # day lead_bp-list -> rows: follower lead_bp total spread inventory fees fills
    local p f l s
    for p in $pairs; do
        IFS=: read -r f l s <<< "$p"
        "$b/apps/itch_backtest" "$d/store-$1-v50" "$f" leader sign="${s:-1}" maker_rebate="$rebate" --index "$l" \
            --sweep lead_bp="$2" | tail -n +2 | sed "s/^/$f\t/"
    done
}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for t in "${train[@]}"; do run "$t" "$grid"; done > "$tmp/train"
best=$(awk '{s[$2]+=$3} END{b=""; for (k in s) if (b=="" || s[k]>s[b]) b=k; print b}' "$tmp/train")
for t in "${test[@]}"; do run "$t" "$best,1000" | sed "s/^/$t\t/"; done > "$tmp/test"

cat <<EOF
# Leader filter, walk-forward

Generated by \`scripts/leader_walkforward.sh\`. Strategy \`leader\`: joins the best bid and ask
(100 shares, inventory cap 500), pulls the side the top-of-book imbalance points against
(threshold 0, as chosen in docs/results/maker-walkforward.md), and also the side the leader's 0.1 s
momentum points against when it exceeds lead_bp. The baseline is the same maker with the leader
ignored (lead_bp = 1000). Pairs follower:leader[:-1 inverse]: $pairs. Train: $(day ${train[0]}),
$(day ${train[1]}); test: $(for t in "${test[@]}"; do day "$t"; done | paste -sd, | sed 's/,/, /g').
Maker rebate: \$$(awk -v r="$rebate" 'BEGIN{printf "%.4f", r/1e6}') per share; zero latency.

Train PnL by lead_bp (USD, all pairs, both days):

| lead_bp | Total | Spread | Inventory | Fills |
|---|---|---|---|---|
$(awk '{t[$2]+=$3; s[$2]+=$4; i[$2]+=$5; f[$2]+=$7} END{for (k in t) printf "| %s | %.0f | %.0f | %.0f | %d |\n", k, t[k], s[k], i[k], f[k]}' "$tmp/train" | sort -t'|' -k2 -g)

Chosen lead_bp: **$best**.

Test days (USD per follower, all test days summed):

| Follower | Leader ignored | With leader | Fills ignored / with |
|---|---|---|---|
$(awk -v best="$best" '{k=$2; if ($3=="1000") {n[k]+=$4; nf[k]+=$8} if ($3==best) {f[k]+=$4; ff[k]+=$8}}
    END{for (k in n) printf "| %s | %.0f | %.0f | %d / %d |\n", k, n[k], f[k], nf[k], ff[k]}' "$tmp/test")

$(awk -v best="$best" '{k=$2; if ($3=="1000") n[k]+=$4; if ($3==best) f[k]+=$4}
    END{for (k in n) {a+=n[k]; c+=f[k]; if (f[k]>n[k]) w++; m++}
        printf "Total: leader ignored %.0f, with leader %.0f; better on %d of %d followers.", a, c, w, m}' "$tmp/test")

| Test day | Leader ignored | With leader |
|---|---|---|
$(for t in "${test[@]}"; do awk -v t="$t" -v best="$best" -v day="$(day "$t")" '$1==t {if ($3=="1000") j+=$4; if ($3==best) f+=$4}
    END{printf "| %s | %.0f | %.0f |\n", day, j, f}' "$tmp/test"; done)
EOF
