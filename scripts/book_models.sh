#!/usr/bin/env bash
# Results page for the order book models on the stored days: multi-level OFI (itch_mlofi), the
# Markov chain of the top of book (itch_markov) and the market realism scorecard (itch_realism).
# Usage: scripts/book_models.sh > docs/results/book-models.md
set -euo pipefail
cd "$(dirname "$0")/.."
B=${HFT_BUILD:-build/native}/apps
D=${HFT_DATA:-$HOME/data}
DAYS=${DAYS:-S101819 S120925 S121025 S121125 S121225}
SYMS=${SYMS:-AAPL MSFT NVDA AMZN INTC}
store() { echo "$D/store-$1-v50"; }

echo "# Order book models"
echo
echo "Generated by \`scripts/book_models.sh\` on $(echo $DAYS | wc -w) stored Nasdaq days. Each tool fits on 09:35 to 12:45 ET and scores on 12:45 to 15:55. Methods: docs/METHODS.md."
echo
echo "## Multi-level OFI, out of sample (median over AAPL, MSFT, NVDA, AMZN, GOOGL)"
echo
echo "| Day | R² best level | R² integrated | R² next interval, own OFI | R² next interval, all symbols |"
echo "|---|---|---|---|---|"
for d in $DAYS; do
    out=$("$B/itch_mlofi" "$(store "$d")" AAPL,MSFT,NVDA,AMZN,GOOGL)
    impact=$(echo "$out" | grep '^| median | | |' | awk -F'|' '{print $5 "|" $6}')
    fc=$(echo "$out" | grep '^| median | -\?[0-9]' | awk -F'|' '{print $3 "|" $4}')
    echo "| $d |$impact|$fc|"
done
echo
echo "## Markov chain of the top of book: direction of the next mid move"
echo
echo "| Day | Symbol | Mid moves scored | Predicted right | Always the more frequent direction |"
echo "|---|---|---|---|---|"
for d in $DAYS; do
    for s in $SYMS; do
        "$B/itch_markov" "$(store "$d")" "$s" | grep -A2 '^| Mid moves' | tail -1 |
            awk -F'|' -v d="$d" -v s="$s" '{print "| " d " | " s " |" $2 "|" $4 "|" $5 "|"}'
    done
done
echo
echo "## Market realism: mean total variation over the ten LOB-Bench statistics"
echo
echo "0 is the same distribution, 1 disjoint. A is the reference symbol-day; with no B the queue-reactive simulator generates it."
echo
echo "| A | B | Mean TV |"
echo "|---|---|---|"
realism() {  # lobiq generates the simulator's day when no B is given
    HFT_BIN=$B HFT_DATA=$D scripts/lobiq realism "$@" | grep '^| \*\*mean' | awk -F'|' '{gsub(/[* ]/, "", $5); print $5}'
}
pairs=("S121025 AAPL S121125 AAPL" "S121025 AAPL S121025 MSFT" "S121025 AAPL S101819 AAPL" "S121025 AAPL" "S121025 NVDA" "S121025 INTC")
for p in "${pairs[@]}"; do
    read -r d1 s1 d2 s2 <<< "$p"
    if [ -n "${d2:-}" ]; then
        echo "| $s1 $d1 | $s2 $d2 | $(realism "$d1" "$s1" "$d2" "$s2") |"
    else
        echo "| $s1 $d1 | simulator | $(realism "$d1" "$s1") |"
    fi
done
