#!/usr/bin/env bash
# Peak numbers: turbo on, one P-core, one E-core and the whole chip. Prints Markdown
# (docs/results/max-performance.md). First: sudo NO_TURBO=0 scripts/tune.sh and scripts/pgo.sh.
set -euo pipefail
cd "$(dirname "$0")/.."
d=${HFT_DATA:-$HOME/data}
day=${DAY:-S121025}
P=${PCPU:-4} E=${ECPU:-12}
[ "$(cat /sys/devices/system/cpu/intel_pstate/no_turbo)" = 0 ] || { echo "turbo is off: sudo NO_TURBO=0 scripts/tune.sh" >&2; exit 2; }
for b in build/native build/pgo-use; do [ -x "$b/apps/book_replay" ] || { echo "missing $b: build it first" >&2; exit 2; }; done
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
msgs=$(awk 'NR>1{s+=$3} END{print s}' <(THREADS=20 build/pgo-use/apps/book_replay "$d/store-$day-v50" tick 2>/dev/null))

hot() { cat /sys/class/thermal/thermal_zone*/temp | sort -n | tail -1; }
idle=$(hot)
# Waits (up to 3 min) until the hottest sensor is back within 5 C of its idle reading at start.
cool() {
    local i
    for i in $(seq 90); do
        [ "$(hot)" -le $((idle + 5000)) ] && return
        sleep 2
    done
}
# One instance per listed CPU at once; prints per-CPU "cpu batch_ns p50 p99 max_us events wall_s".
book_on() {
    local c
    cool
    for c in "$@"; do
        ( s=$(date +%s.%N); o=$(taskset -c "$c" build/native/bench/book_study "$d/store-S120825-v50" book:tick 1 3 1 2>/dev/null | tail -3)
          e=$(date +%s.%N)
          echo "$o" | awk -F, -v c="$c" -v w="$(awk -v s="$s" -v e="$e" 'BEGIN{print e-s}')" \
              '{t+=$5; a+=$6; b+=$7; m=$9>m?$9:m; n++; ev=$4} END{printf "%s %.1f %.1f %.1f %.0f %d %.3f\n", c, t/n/ev, a/n, b/n, m/1000, ev*n, w}' ) &
    done
    wait
}
pm_on() {  # same, for pm_live --replay: "cpu parse_p50 parse_p99 engine_p50 engine_p99 wall_s"
    local c
    cool
    for c in "$@"; do
        ( s=$(date +%s.%N); o=$(taskset -c "$c" build/pgo-use/apps/pm_live --replay "$d/pm-live/20261009T160027Z" 2>&1)
          e=$(date +%s.%N)
          echo "$o" | grep -oE 'parse [0-9/]+ engine [0-9/]+' | tr '/' ' ' |
              awk -v c="$c" -v s="$s" -v e="$e" '{printf "%s %s %s %s %s %.3f\n", c, $2, $3, $6, $7, e-s}' ) &
    done
    wait
}
# Mean of columns 2.. over the rows whose CPU is in [lo, hi].
mean() { awk -v lo="$1" -v hi="$2" '$1>=lo && $1<=hi {n++; for (i=2; i<=NF; i++) s[i]+=$i} END{for (i=2; i<=NF; i++) printf "%s ", s[i]/n; print ""}'; }
book_row() { awk '{printf "%.1f | %.1f | %.1f | %.0f", $1, $2, $3, $4}'; }
pm_row() { awk '{printf "%.0f / %.0f | %.0f / %.0f | %.2fM", $1, $2, $3, $4, 1982218/$5/1e6}'; }
chip_rate() {  # book: summed batch rates; pm: all messages over the slowest instance's wall time
    awk -v per="$1" '{n++; w=$NF>w?$NF:w; r+=1e9/$2} END{if (per=="book") printf "%.0fM", r/1e6; else printf "%.1fM", n*1982218/w/1e6}'
}
replay() {  # threads cpus -> "seconds | M messages/s"
    local s e
    cool
    s=$(date +%s.%N)
    THREADS=$1 taskset -c "$2" build/pgo-use/apps/book_replay "$d/store-$day-v50" tick >/dev/null 2>&1
    e=$(date +%s.%N)
    awk -v s="$s" -v e="$e" -v m="$msgs" 'BEGIN{printf "%.2f | %.1fM", e-s, m/(e-s)/1e6}'
}

cat <<EOF
# Peak performance

Generated by \`scripts/bench_max.sh\` on the i7-13650HX laptop (docs/exec/HW.md), turbo on, governor
and platform profile performance, uncore pinned at its maximum, on AC power. CPU $P is a 4.9 GHz
P-core, CPU $E a 3.6 GHz E-core; whole-process pinning with taskset. Other tables in the repository
run with turbo off for stable before/after comparisons; these are the ceiling. Each run starts
within 5 C of the idle temperature; whole-chip runs are power and thermal limited.

## Order book (book_study book:tick, S120825-v50, busiest symbol, 14.1M events, native build)

"Alone": one instance on an otherwise idle chip. "Whole chip": 20 instances at once, one per
hardware thread (both SMT threads of every P-core busy), averaged over the P-core threads (CPUs 0-11)
and over the E-cores (12-19).

| Run | Batch ns/event | p50 ns | p99 ns | Max us |
|---|---|---|---|---|
| P-core alone (CPU $P) | $(book_on "$P" | mean 0 99 | book_row) |
| E-core alone (CPU $E) | $(book_on "$E" | mean 0 99 | book_row) |
$(book_on $(seq 0 19) > "$tmp/chip_book"; echo "| Whole chip, P-core threads | $(mean 0 11 < "$tmp/chip_book" | book_row) |")
| Whole chip, E-cores | $(mean 12 19 < "$tmp/chip_book" | book_row) |

Whole chip: $(chip_rate book < "$tmp/chip_book") book updates/s over 20 instances.

## Prediction-market replay (pm_live --replay, 2.0M messages, PGO build)

| Run | Parse p50 / p99 ns | Engine p50 / p99 ns | Messages/s per instance |
|---|---|---|---|
| P-core alone (CPU $P) | $(pm_on "$P" | mean 0 99 | pm_row) |
| E-core alone (CPU $E) | $(pm_on "$E" | mean 0 99 | pm_row) |
$(pm_on $(seq 0 19) > "$tmp/chip_pm"; echo "| Whole chip, P-core threads | $(mean 0 11 < "$tmp/chip_pm" | pm_row) |")
| Whole chip, E-cores | $(mean 12 19 < "$tmp/chip_pm" | pm_row) |

Whole chip: $(chip_rate pm < "$tmp/chip_pm") messages/s over 20 instances.

## Full Nasdaq day ($day, $msgs messages, 12,000+ symbols, book_replay, PGO build)

| Run | Seconds | Messages/s |
|---|---|---|
| 1 thread, P-core (CPU $P) | $(replay 1 "$P") |
| 1 thread, E-core (CPU $E) | $(replay 1 "$E") |
| 16 threads, non-isolated CPUs | $(replay 16 0-3,8-19) |
| 20 threads, all 20 CPUs | $(replay 20 0-19) |
EOF
